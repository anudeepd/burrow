#!/usr/bin/env python3
"""Generates docs/parity.md from the inventory (single source of truth: the YAML files).

  .venv/bin/python parity/inventory/tools/gen_parity_doc.py [--write]

Without --write it prints to stdout.  The prose lives here so the document can never drift from the data.
"""
import glob
import json
import os
import sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
INV = os.path.abspath(os.path.join(HERE, '..'))
ROOT = os.path.abspath(os.path.join(INV, '..', '..'))
DOC = os.path.join(ROOT, 'docs', 'parity.md')

import yaml  # noqa: E402


def load(p):
    with open(p) as f:
        return yaml.safe_load(f)


def esc(s):
    return str(s if s is not None else '').replace('|', '\\|').replace('\n', ' ')


def main():
    rest = load(os.path.join(INV, 'rest-schema.yaml'))
    reg = load(os.path.join(INV, 'field-ids.yaml'))
    pages = []
    for f in [os.path.join(INV, 'legacy-pages.yaml'), os.path.join(INV, 'ui2.yaml'), os.path.join(INV, 'ui2-extra.yaml')]:
        if os.path.exists(f):
            pages.append((os.path.relpath(f, ROOT), load(f)))
    rows = {r['id']: r for r in reg['fields']}
    entities = {e['id']: e for e in rest['entities']}
    resources = {r['id']: r for r in rest['resources']}

    out = []
    w = out.append

    n_pages = sum(len(d.get('pages') or []) for _, d in pages)
    n_sections = sum(len(p.get('sections') or []) for _, d in pages for p in d.get('pages') or [])
    n_items = sum(len(s.get('items') or []) for _, d in pages for p in d.get('pages') or [] for s in p.get('sections') or [])
    by_origin = Counter(r['origin'] for r in reg['fields'])
    by_status = Counter(r['status'] for r in reg['fields'])
    by_shown = Counter(','.join(sorted(r['shownBy'])) or 'rest-only' for r in reg['fields'])
    by_cat = Counter((r.get('waiver') or {}).get('category') for r in reg['fields'] if r['status'] == 'waivable')
    legacy_items = sum(1 for _, d in pages for p in d.get('pages') or [] if p['id'].startswith('legacy.')
                       for s in p.get('sections') or [] for _ in s.get('items') or [])
    ui2_items = n_items - legacy_items

    w('# Parity inventory — method, field ids and per-page mapping\n')
    w('> Generated by `parity/inventory/tools/gen_parity_doc.py` from `parity/inventory/*.yaml`. '
      'Do not hand-edit: edit the YAML (or this script for prose) and regenerate.\n')
    w('This is the **P0 ground truth** of PLAN.md §8: for every field a stock YARN UI shows, the label, its canonical '
      'field id (`docs/contracts/parity-dom.md`), where the value comes from in the RM/NM/JHS REST API (or why it has '
      'no REST source: `derived`), the display format and the normaliser the differential harness needs.\n')
    w('Everything here is derived from the **Hadoop 3.4.3 sources** (`.cluster/src-extract/`, extracted by '
      '`parity/inventory/tools/extract-sources.sh`) plus the **compiled UI2 bundle** in '
      '`.cluster/hadoop/share/hadoop/yarn/webapps/ui2` (split/decoded by `tools/ui2_extract.py` + '
      '`tools/ui2_decode_templates.js`). Nothing is quoted from memory; every item carries a `source: file:line` '
      'pointer and every REST object/field a DAO source line.\n')

    w('## 1. How to reproduce\n')
    w('```sh')
    w('# 1. sources (idempotent; needs the Hadoop tree from cluster provisioning)')
    w('parity/inventory/tools/extract-sources.sh')
    w('# 2. per-module REST/legacy extracts (each writes one src/*.yaml file)')
    w('.venv/bin/python parity/inventory/tools/gen_rest_rm.py        # src/rest-rm.yaml  (RM REST objects+resources)')
    w('.venv/bin/python parity/inventory/tools/gen_rest_nm.py        # src/rest-nm.yaml  (NM REST objects+resources)')
    w('bun parity/inventory/tools/ui2_extract.py                      # ui2 bundle -> .cluster/src-extract/ui2')
    w('bun parity/inventory/tools/ui2_decode_templates.js             # compiled HTMLBars -> readable .hbs.txt')
    w('# 3. merge + registry + validation (all offline)')
    w('.venv/bin/python parity/inventory/build.py                     # rest-schema.yaml, legacy-pages.yaml, field-ids.yaml')
    w('.venv/bin/python parity/inventory/validate.py                  # JSON Schema + referential integrity + totals')
    w('.venv/bin/python parity/inventory/tools/gen_parity_doc.py --write   # this document')
    w('')
    w('# 4. optional live shape check against the running cluster (P1-lite: every registered REST id path must resolve)')
    w('.venv/bin/python parity/inventory/tools/live_probe.py')
    w('```\n')
    w('`build.py` is idempotent; `validate.py` exits 1 on any failure and is the gate for this slice. '
      'The per-page extracts under `src/` are hand-curated (labels verbatim from the Java, `source:` pointers) but '
      'their *shapes* are machine-checked: `validate.py` proves every `field:` resolves to a registry row and every '
      'REST JSON path reachable from a GET resource is either registered or explicitly waived.\n')

    w('## 2. Totals\n')
    w('| what | count |')
    w('|---|---|')
    w('| inventory pages | %d (%d legacy, %d UI2) |' % (n_pages, sum(1 for _, d in pages for p in d.get('pages') or [] if p['id'].startswith('legacy.')), sum(1 for _, d in pages for p in d.get('pages') or [] if p['id'].startswith('ui2.'))))
    w('| sections | %d |' % n_sections)
    w('| items (labels/columns/links/charts) | %d (%d legacy, %d UI2) |' % (n_items, legacy_items, ui2_items))
    w('| REST entities | %d |' % len(rest['entities']))
    w('| REST objects (DAO shapes) | %d |' % len(rest['objects']))
    w('| REST object fields (Java members serialised) | %d |' % sum(len(o['fields']) for o in rest['objects'].values()))
    w('| REST resources (endpoints) | %d |' % len(rest['resources']))
    w('| derived (non-REST) declarations | %d |' % (by_origin['derived']))
    w('| field-id registry rows | %d (rest %d, derived %d, static %d) |' % (len(reg['fields']), by_origin['rest'], by_origin['derived'], by_origin['static']))
    w('| registry: required (a legacy/UI2 item renders it) | %d |' % by_status['required'])
    w('| registry: waivable (with a reason) | %d |' % by_status['waivable'])
    w('| registry shownBy legacy / ui2 / both / rest-only | %d / %d / %d / %d |' % (by_shown['legacy'], by_shown['ui2'], by_shown['legacy,ui2'], by_shown['rest-only']))
    w('| REST JSON paths waived without a field id | %d |' % len(reg.get('unmappedPaths') or []))
    w('')
    w('Waiver categories (each row in `field-ids.yaml` carries a `waiver.reason`; there are no silent skips):\n')
    w('| category | rows |')
    w('|---|---|')
    for cat, n in by_cat.most_common():
        w('| %s | %d |' % (cat, n))
    w('')
    w('`rest-only` rows are keys the stock UIs do **not** render (they are still catalogued so PLAN §8 P1 can prove '
      'the SPA does not miss them); `composite` rows are whole `Resource` objects that YARN prints as one formatted '
      'string, e.g. `queue.resourcesUsed` -> `"<memory:1024, vCores:2>"`.\n')

    w('## 3. Method\n')
    w('### 3.1 Where labels come from\n')
    w('* **Legacy Hamlet UI**: the Java `*Block`/`*Page`/`*Table` classes under '
      '`hadoop-yarn-server-resourcemanager/.../webapp/`, `hadoop-yarn-server-common/.../webapp/` and '
      '`hadoop-yarn-common/.../webapp/view/`. Labels are the verbatim string literals of the Hamlet calls '
      '(`.th(".id", "Attempt ID")`, `.h3("Scheduler Health")`, `info(..).__("Queue State:", …)`); DataTables column '
      'class names (`<th class=".allocatedMB">`) are recorded in `note:` because the legacy table feeds the DOM '
      '*class* to the renderer (`yarn.dt.plugins.js` renderHadoopDate/parseHadoopProgress).\n')
    w('* **UI2 (Ember)**: the compiled bundle is split into modules and its precompiled HTMLBars templates are '
      'decoded back to pseudo-Handlebars, so literal labels are exact; column definitions come from '
      '`yarn-ui/controllers/*-table-columns.js` / component `columns` arrays, REST paths from '
      '`yarn-ui/adapters/*.js`, and attribute names from `yarn-ui/models/*.js`.\n')
    w('### 3.2 Field ids\n')
    w('`<entity>.<JSON key path relative to the entity object>` with array indices dropped (see '
      '`docs/contracts/parity-dom.md`). Entities are declared once, in a REST part (`src/rest-*.yaml`), because the '
      'id must be derivable from the upstream JSON. Values the stock UI computes instead of printing a REST key get '
      '`<entity>.derived.<camelName>` declared once with the Java/JS expression that produces them. Pure chrome gets '
      '`static.<name>`.\n')
    w('### 3.3 REST shapes (JAXB/Jersey) — the parts that bite\n')
    w('Hadoop 3.4.3 serialises RM/NM/AHS/JHS DAOs through Jersey 1 `JSONJAXBContext`. Three behaviours are '
      'live-verified against the running cluster (2026-10-03) and are recorded per object as `jsonMode`:\n')
    w('| mode | who | behaviour |')
    w('|---|---|---|')
    w('| `wrapped` | classes in `JAXBContextResolver` `cTypes` | body is `{"<xmlRoot>":{…}}`, native JSON types (`{"apps":{"app":[…]}}`, `"progress":100.0`) |')
    w('| `unwrapped` | classes in `rootUnwrappedTypes` | root element dropped, native types (`{"priority":0}`) |')
    w('| `unwrapped-stringified` | every other class (Jersey default provider) | root dropped **and every scalar stringified** (`{"allocatedMB":"768"}`, `"exclusivity":"false"`) |')
    w('| `nested` | objects only used inside another object | inherits the parent context |')
    w('')
    w('Other quirks that the harness must normalise (each also noted on the field):\n')
    w('* **null properties are omitted**, not emitted as `null` (e.g. `ClusterInfo.subClusterId`, `NodeInfo.healthReport` is `""` though).\n')
    w('* **`-1` sentinels**: `AppInfo.allocatedMB/allocatedVCores/reservedMB/reservedVCores/runningContainers` are `-1` '
      'for finished applications; `AppTimeoutInfo.remainingTimeInSeconds` is `-1` with `expiryTime:"UNLIMITED"` when unset.\n')
    w('* **single-element collections collapse** to a bare element in the fallback/stringified contexts '
      '(`/nodes/x/get-labels` with one label) and for JAXB map adapters with one entry '
      '(`AppInfo.resourceSecondsMap` -> `{"entry":{"key":..,"value":..}}`). Arrays of DAO objects in wrapped '
      'contexts stay arrays even with one element (live-verified with a 1-application `/apps?states=FAILED`).\n')
    w('* **maps** are serialised through the JAXB map adapter as `{"entry":[{"key":…,"value":…}, …]}`.\n')
    w('* **empty results omit the key**: `/apps` with no match is `{"apps":{}}`, `/…/containers` is `{}`.\n')
    w('* **`type` discriminators**: `capacityScheduler` / `fairScheduler` / `fifoScheduler` / `capacitySchedulerLeafQueueInfo` … '
      'are injected by the JSON provider from `@XmlType`/the class name, not Java fields (registry rows marked `synthetic`).\n')
    w('* `SchedulerInfo` is an abstract base whose protected fields are **not** serialised under the subclasses\' '
      '`@XmlAccessorType(FIELD)`; only the discriminator appears.\n')

    w('### 3.4 Conditional pages and items\n')
    w('`when:` uses the vocabulary in FORMAT.md (`scheduler=capacity|fair|fifo`, `state=…`, `conf:x=y`, `labels`, `ha`, '
      '`secure`, `value:null|-1|non-empty`, `ui:<flag>`, `other:…`). Items that only appear with a particular cluster '
      'state also carry `scenario:` (what must exist on the test cluster to see them). '
      'Every such item is listed in §6.\n')

    w('## 4. Per-page mapping (label -> field id -> REST source -> format)\n')
    w('`REST` is `<resource id> @ <JSON path from the response body>`; empty means the value is derived (the '
      '`derivation` column shows the Java/JS expression) or static chrome. `fmt`/`norm` are the display format and the '
      'normaliser the differential harness applies to the legacy text.\n')
    for relpath, doc in pages:
        for p in doc.get('pages') or []:
            w('### `%s` — %s' % (p['id'], esc(p.get('title'))))
            w('')
            w('* file: `%s`; daemon: `%s`; route: `%s`' % (relpath, p['daemon'], esc(p['route'])))
            if p.get('classes'):
                w('* classes: %s' % ', '.join('`%s`' % c for c in p['classes']))
            if p.get('includes'):
                w('* includes: %s' % ', '.join('`%s`' % c for c in p['includes']))
            if p.get('when'):
                w('* available when: %s' % ', '.join('`%s`' % c for c in p['when']))
            if p.get('query'):
                w('* query params: %s' % ', '.join('`%s` — %s' % (q.get('name'), esc(q.get('doc'))) for q in p['query']))
            w('')
            for s in p.get('sections') or []:
                w('#### %s%s' % (s['id'], (' — %s' % esc(s['title'])) if s.get('title') else ''))
                w('')
                w('| label | kind | field id | REST | fmt | norm | when | source |')
                w('|---|---|---|---|---|---|---|---|')
                for it in s.get('items') or []:
                    fid = it.get('field') or ''
                    row = rows.get(fid) or {}
                    rr = it.get('rest') or {}
                    if rr.get('resource'):
                        rest_cell = '%s @ `%s`' % (rr['resource'], esc(rr.get('path')))
                    elif row.get('rest'):
                        rest_cell = '<br>'.join('%s @ `%s`' % (e['resource'], esc(e['jsonPath'])) for e in row['rest'][:2])
                    elif row.get('origin') == 'derived' or '.derived.' in fid:
                        rest_cell = '_derived_'
                    elif row.get('composite'):
                        rest_cell = '<br>'.join('%s @ `%s`' % (e['resource'], esc(e['jsonPath'])) for e in row['rest'][:2])
                    else:
                        rest_cell = ''
                    deriv = it.get('derivation') or row.get('derivation') or ''
                    if deriv:
                        rest_cell = (rest_cell + '<br>' if rest_cell else '') + '`%s`' % esc(deriv[:180])
                    w('| %s | %s | `%s` | %s | %s | %s | %s | `%s` |' % (
                        esc(it.get('label')) or '_(none)_', it.get('kind'), fid, rest_cell,
                        esc(it.get('format')), esc(it.get('normaliser') or 'none'),
                        '<br>'.join(['`%s`' % c for c in (it.get('when') or [])]) + (('<br>_scenario:_ %s' % esc(it['scenario'])) if it.get('scenario') else ''),
                        esc(it.get('source'))))
                w('')

    w('## 5. REST resource coverage\n')
    w('Every RM/NM/JHS/AHS/daemon resource a legacy or UI2 page uses is declared, including the ones **outside** the '
      '`docs/contracts/api.md` allowlist (`allowlist: false`) so nothing is invisible. Write endpoints are listed with '
      '`readOnly: false` and excluded from the product.\n')
    w('| resource | daemon | method | path | in contract | read-only | response root |')
    w('|---|---|---|---|---|---|---|')
    for r in rest['resources']:
        resp = r.get('response') or {}
        w('| `%s` | %s | %s | `%s` | %s | %s | %s |' % (
            r['id'], r['daemon'], r['method'], r['path'], 'yes' if r['allowlist'] else 'no',
            'yes' if r['readOnly'] else '**no (write)**',
            ('`%s` %s' % (esc(resp.get('jsonRoot')), 'unwrapped' if resp.get('object') and not resp.get('jsonRoot') else '')) or '_non-JSON_'))
    w('')

    w('## 6. Items that need a scenario (or a feature) to be visible\n')
    w('| page | item | field id | when / scenario |')
    w('|---|---|---|---|')
    cond = 0
    for relpath, doc in pages:
        for p in doc.get('pages') or []:
            for s in p.get('sections') or []:
                for it in s.get('items') or []:
                    conds = list(it.get('when') or [])
                    if p.get('when'):
                        conds += ['page: ' + c for c in p['when']]
                    if it.get('scenario'):
                        conds.append('scenario: ' + it['scenario'])
                    if conds:
                        cond += 1
                        w('| %s | %s | `%s` | %s |' % (p['id'], esc(it.get('label')) or it['id'], it.get('field'),
                                                       '<br>'.join('`%s`' % c for c in conds)))
    if cond == 0:
        w('| _none_ | | | |')
    w('')

    w('## 7. Values with no REST source (`restGap`)\n')
    w('These are shown by YARN but not exposed by any contracted endpoint. Where the information is obtainable '
      'elsewhere the `altSource` says how (usually `/jmx`); otherwise the SPA cannot reproduce the exact value and the '
      'harness must waive it explicitly.\n')
    w('| derived id | entity | derivation | alt source |')
    w('|---|---|---|---|')
    deriv_rows = [d for d in rest.get('derived', [])] 
    for relpath, doc in pages:
        deriv_rows += list(doc.get('derived') or [])
    for d in deriv_rows:
        if d.get('restGap'):
            w('| `%s` | %s | `%s` | %s |' % (d['id'], d.get('entity'), esc(d.get('derivation'))[:160], esc(d.get('altSource')) or '_none_'))
    w('')

    w('## 8. Honest "needs live verification" list\n')
    w('Everything below is source-derived and structurally verified, but a claim in it has **not** been confirmed '
      'against a live daemon. `[INFERENCE]` appears in the corresponding `note`. PLAN §8 P1/P2 must confirm each one '
      'before it is treated as ground truth.\n')
    gaps = []
    for relpath, doc in pages:
        for p in doc.get('pages') or []:
            for s in p.get('sections') or []:
                for it in s.get('items') or []:
                    for txt in [it.get('note') or '', it.get('derivation') or '']:
                        if 'INFERENCE' in txt or 'verify live' in txt:
                            gaps.append((p['id'], it['id'], esc(txt)[:300]))
                            break
    for d in deriv_rows:
        if 'INFERENCE' in (d.get('altSource') or '') or 'verify' in (d.get('note') or ''):
            gaps.append(('-', d['id'], esc(d.get('altSource') or d.get('note'))[:300]))
    w('| page | item | why |')
    w('|---|---|---|')
    if gaps:
        for pid, iid, why in gaps:
            w('| %s | `%s` | %s |' % (pid, iid, why))
    else:
        w('| _none_ | | |')
    w('')
    w('Known environmental facts that must be re-checked per YARN version (all verified on 3.4.3 today):\n')
    w('* `rm.resource-profiles`, `rm.resource-types`, `rm.containers` are in the api.md allowlist but are **not '
      'registered by this build** (live 404) — see the contract change requests.\n')
    w('* The `/conf` content negotiation is **`Accept`-driven**: `?format=json` is ignored (live-verified), so the '
      'backend must send `Accept: application/json` for `{"properties":[…]}` and the API contract line mentioning '
      '`?format=json` is wrong.\n')
    w('* `apps/{appId}/appactivities` in api.md §3 does not exist; the real path is `/scheduler/app-activities/{appid}`.\n')
    w('Shape check performed on 2026-10-03 with `tools/live_probe.py` against the live RM (capacity scheduler, 3 NMs, '
      '~30 applications): 643 registered RM id paths resolved, 331 were absent for the then-current cluster state '
      '(optional/null fields such as `AppInfo.appNodeLabelExpression`, `PartitionResourcesInfo.amLimit`, '
      '`ResourceInformation.tags`, or scheduler activities that need `yarn.resourcemanager.scheduler.activities.enable`), '
      '0 wrong paths; the NM/JHS/AHS ids are probed with `--all`.\n')

    w('## 9. Contract change requests (for the integration owner)\n')
    w('The inventory is the authority for the field ids, so these are the places where `docs/contracts/api.md` and '
      '`docs/contracts/parity-dom.md` disagree with the real 3.4.3 daemons:\n')
    w('1. **api.md §3**: add `scheduler-overview` (it is the 1:1 source of the legacy scheduler info block and is '
      'already rendered by the SPA), `userinfo`, `apps/{appId}/appattempts/{attemptId}` and '
      '`nodes/{nodeId}/get-labels`. Remove or mark unsupported `resource-profiles`, `resource-types`, '
      '`containers/{containerId}` (all 404 on 3.4.3).\n')
    w('2. **api.md §3**: replace `apps/{appId}/appactivities` with `scheduler/app-activities/{appId}`.\n')
    w('3. **api.md §3 daemon pages**: `/conf` is `Accept`-driven (no `?format=json`); `/metrics` is not registered by '
      'the RM in 3.4.3 (404) and must be dropped or feature-gated.\n')
    w('4. **parity-dom.md §Field-id grammar**: the entity list needs the entities this inventory actually declares '
      '(listed in `rest-schema.yaml`), notably `clusteruser`, `usermetrics`, `queueuser`, `activities`, `appactivity`, '
      '`timeout`, `queueacl`, `jmx`, `log`, `conf`, the `nm.*` family and the UI2-only `ats*` entities; and the '
      '`data-yv` rule should say that stringified upstream scalars keep the upstream spelling (`"768"`).\n')
    w('5. **PLAN §8 P1**: the waivers for REST keys the stock UI does not render belong in `parity/waivers.yaml`; '
      '`field-ids.yaml` (`status: waivable` + `waiver.reason`) is the input list for it.\n')

    w('## 10. File map\n')
    w('| file | role |')
    w('|---|---|')
    w('| `parity/inventory/FORMAT.md` | binding format spec for every file below |')
    w('| `parity/inventory/schema.json` | JSON Schema (draft 2020-12) for all files |')
    w('| `parity/inventory/build.py` | merge + registry builder (idempotent) |')
    w('| `parity/inventory/validate.py` | schema + referential integrity + class accounting + totals (exit 1 on failure) |')
    for r in sorted(glob.glob(os.path.join(INV, 'src', '*.yaml'))):
        w('| `src/%s` | hand-curated extract (REST part or legacy page part) |' % os.path.basename(r))
    for r in ['ui2.yaml', 'ui2-extra.yaml', 'rest-schema.yaml', 'legacy-pages.yaml', 'field-ids.yaml']:
        w('| `%s` | %s |' % (r, 'hand-curated UI2 pages' if r.startswith('ui2') else 'GENERATED by build.py'))
    w('| `tools/` | extraction tooling (sources, DAO parser, NM/RM generators, UI2 splitter/decoder, this doc generator) |')
    w('')
    w('## 11. Validator snapshot\n')
    w('```')
    w('%d entities, %d objects (%d object fields), %d resources' % (len(rest['entities']), len(rest['objects']), sum(len(o['fields']) for o in rest['objects'].values()), len(rest['resources'])))
    w('%d pages, %d sections, %d items' % (n_pages, n_sections, n_items))
    w('registry: %d rows (rest %d, derived %d, static %d); required %d, waivable %d' % (len(reg['fields']), by_origin['rest'], by_origin['derived'], by_origin['static'], by_status['required'], by_status['waivable']))
    w('REST paths waived without a field id: %d' % len(reg.get('unmappedPaths') or []))
    w('```')
    w('')
    text = '\n'.join(out)
    if '--write' in sys.argv:
        with open(DOC, 'w') as f:
            f.write(text + '\n')
        print('wrote %s (%d lines)' % (DOC, text.count('\n') + 1))
    else:
        print(text)


if __name__ == '__main__':
    main()
