#!/usr/bin/env python3
"""Builds the generated inventory artifacts (idempotent).

  .venv/bin/python parity/inventory/build.py

Inputs                                    Outputs
  src/rest-*.yaml                        -> rest-schema.yaml   (merged REST object model)
  src/legacy-*.yaml                      -> legacy-pages.yaml  (merged legacy Hamlet/daemon pages)
  rest-schema.yaml + legacy-pages.yaml
   + ui2.yaml + ui2-extra.yaml
   + src/field-overrides.yaml            -> field-ids.yaml     (canonical field-id registry)

Object/entity/resource ids must be unique repo-wide: a clash is a hard error, because the field-id grammar
(and therefore the parity DOM contract) depends on it.  Edit `src/field-overrides.yaml`, not `field-ids.yaml`.
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'tools'))
from invlib import ROOT, OUT  # noqa: E402

import yaml  # noqa: E402

INV = os.path.join(ROOT, 'parity', 'inventory')
SRC = os.path.join(INV, 'src')
GENERATED = 'GENERATED by parity/inventory/build.py - do not hand-edit.'


def load(path):
    with open(path) as f:
        return yaml.safe_load(f)


def dump_yaml(path, data, header):
    with open(path, 'w') as f:
        f.write('# %s\n' % header)
        yaml.safe_dump(data, f, sort_keys=False, width=100000, allow_unicode=True)
    return path


def norm(p):
    """Normalise a JSON path for identity comparisons: drop array markers and stray dots."""
    return re.sub(r'\[\]', '', p or '').strip('.')


# --------------------------------------------------------------------------- merge REST parts
def merge_rest():
    parts = sorted(glob.glob(os.path.join(SRC, 'rest-*.yaml')))
    merged = {'version': 1, 'generated': GENERATED, 'entities': [], 'objects': {}, 'resources': [], 'derived': []}
    owners = {}
    seen_entity, seen_resource, seen_derived = {}, {}, {}
    errors = []
    for path in parts:
        rel = os.path.relpath(path, ROOT)
        d = load(path)
        for e in d.get('entities', []):
            if e['id'] in seen_entity:
                errors.append('entity %s declared in both %s and %s' % (e['id'], seen_entity[e['id']], rel))
            seen_entity[e['id']] = rel
            merged['entities'].append(e)
        for name, obj in (d.get('objects') or {}).items():
            if name in merged['objects']:
                errors.append('object %s declared in both %s and %s' % (name, owners[name], rel))
            owners[name] = rel
            merged['objects'][name] = obj
        for r in d.get('resources', []):
            if r['id'] in seen_resource:
                errors.append('resource %s declared in both %s and %s' % (r['id'], seen_resource[r['id']], rel))
            seen_resource[r['id']] = rel
            merged['resources'].append(r)
        for dv in d.get('derived', []):
            if dv['id'] in seen_derived:
                errors.append('derived %s declared in both %s and %s' % (dv['id'], seen_derived[dv['id']], rel))
            seen_derived[dv['id']] = rel
            merged['derived'].append(dv)
    if errors:
        print('\n'.join('ERROR ' + e for e in errors))
        sys.exit(2)
    merged['sources'] = [os.path.relpath(p, ROOT) for p in parts]
    return merged


def merge_legacy():
    parts = sorted(glob.glob(os.path.join(SRC, 'legacy-*.yaml')))
    merged = {'version': 1, 'generated': GENERATED, 'derived': [], 'pages': []}
    seen_page, seen_derived = {}, {}
    errors = []
    for path in parts:
        rel = os.path.relpath(path, ROOT)
        d = load(path)
        for dv in d.get('derived', []) or []:
            if dv['id'] in seen_derived:
                errors.append('derived %s declared in both %s and %s' % (dv['id'], seen_derived[dv['id']], rel))
            seen_derived[dv['id']] = rel
            merged['derived'].append(dv)
        for p in d.get('pages', []) or []:
            if p['id'] in seen_page:
                errors.append('page %s declared in both %s and %s' % (p['id'], seen_page[p['id']], rel))
            seen_page[p['id']] = rel
            p = dict(p)
            p['sourceFiles'] = p.get('sourceFiles') or [rel]
            merged['pages'].append(p)
    if errors:
        print('\n'.join('ERROR ' + e for e in errors))
        sys.exit(2)
    merged['sources'] = [os.path.relpath(p, ROOT) for p in parts]
    return merged


# --------------------------------------------------------------------------- registry
class Registry:
    def __init__(self, rest):
        self.objects = rest['objects']
        self.entities = {e['id']: e for e in rest['entities']}
        self.resources = {r['id']: r for r in rest['resources']}
        self.rows = {}
        self.containers = {}        # (entity, relative path) -> [(resource, json path)] : composite candidates
        self.unmapped = []          # (resource id, json path, reason)
        self.root_obj = {}          # (object name, normalised path) -> entity id
        for e in rest['entities']:
            for r in e['roots']:
                if r.get('object'):
                    self.root_obj[(r['object'], norm(r['jsonPath']))] = e['id']
        self.subs = {}
        for n, o in self.objects.items():
            if o.get('extends'):
                self.subs.setdefault(o['extends'], []).append(n)
        # every object that is the root of each entity: entering any of them makes the others "self" types
        self.entity_roots = {}
        for e in rest['entities']:
            objs = {r['object'] for r in e['roots'] if r.get('object')}
            for o in objs:
                self.entity_roots.setdefault(e['id'], set()).update(objs)

    # -- helpers ----------------------------------------------------------
    def fields_of(self, name, seen=()):
        o = self.objects.get(name)
        if not o:
            return []
        out = []
        ext = o.get('extends')
        if ext and ext in self.objects and ext not in seen:
            out += self.fields_of(ext, seen + (name,))
        return out + o['fields']

    def descendants(self, name):
        out = [name]
        for s in self.subs.get(name, []):
            out += self.descendants(s)
        return out

    def add_container(self, eid, relpath, restpath, resource):
        key = (eid, relpath)
        self.containers.setdefault(key, [])
        entry = {'resource': resource, 'jsonPath': restpath}
        if entry not in self.containers[key]:
            self.containers[key].append(entry)

    def add(self, eid, relpath, restpath, f, resource):
        rid = '%s.%s' % (eid, relpath)
        row = self.rows.get(rid)
        if row is None:
            row = self.rows[rid] = {
                'id': rid, 'entity': eid, 'path': relpath, 'origin': 'rest', 'rest': [],
                'type': f.get('type'), 'unit': f.get('unit') or '', 'nullable': bool(f.get('nullable')),
                'when': [], 'shownBy': [], 'legacyItems': [], 'ui2Items': [],
                'format': 'none', 'normaliser': 'none', 'status': 'required', 'note': f.get('note') or '',
            }
        if f.get('synthetic'):
            row['synthetic'] = True
        for cond in f.get('when') or []:
            if cond not in row['when']:
                row['when'].append(cond)
        entry = {'resource': resource, 'jsonPath': restpath}
        if entry not in row['rest']:
            row['rest'].append(entry)

    def entity_at(self, objname, path):
        hit = self.root_obj.get((objname, norm(path)))
        if hit:
            return hit
        return None

    def switch_for(self, ref, path):
        """All (object, entity) pairs whose root sits exactly at `path` for `ref` or one of its subclasses."""
        out = []
        for d in self.descendants(ref):
            h = self.root_obj.get((d, norm(path)))
            if h:
                out.append((d, h))
        return out

    def rel_of(self, path, prefix, fallback):
        p = norm(path)
        pref = norm(prefix)
        if pref and p.startswith(pref + '.'):
            return p[len(pref) + 1:]
        if pref and p == pref:
            return fallback
        return p or fallback

    # -- walk -------------------------------------------------------------
    # `ancestors` is the set of object names on the current descent path; descending into an object that is
    # already an ancestor would loop forever (ActivityNodeInfo.children, CapacitySchedulerQueueInfo.queues).
    # Entering an entity root resets it, because from there the id path restarts at the entity's own root.
    def walk_object(self, resource, objname, path, entity, prefix, depth=0, ancestors=frozenset(),
                    ent_roots=frozenset()):
        if depth > 14 or objname in ancestors:
            return
        ancestors = ancestors | {objname}
        for f in self.fields_of(objname):
            name = f['name']
            p = (path + '.' + name) if path else name
            if f.get('type') in ('object', 'map') and f.get('ref'):
                self.walk_composite(resource, f, p, entity, prefix, depth, ancestors, ent_roots)
            else:
                self.leaf(resource, f, p, entity, prefix)

    def walk_composite(self, resource, f, p, entity, prefix, depth, ancestors, ent_roots=frozenset()):
        ref = f['ref']
        if ref in ancestors:
            return
        if ref in ent_roots:
            # self-recursive entity structure (a queue nested inside a queue, an activity node inside an activity
            # node): the nested instances expose the SAME entity-relative keys, which the entity's own root has
            # already registered. Stop so the registry does not accumulate duplicate deep paths.
            return
        if entity is not None:
            self.add_container(entity, self.rel_of(p, prefix, f['name']), p, resource['id'])
        if f.get('type') == 'map':
            # JAXB map adapter shape: {"entry":[{"key":..,"value":..}]} (a single entry collapses to an object).
            if f.get('mapKey') and f['mapKey'] not in self.objects:
                self.unmapped.append((resource['id'], p + '.entry[].key',
                                      'map key is a scalar identity, not a value (see field-overrides.unmappedPaths)'))
            cands = []
            for path_try in (p + '.entry[].value', p + '.value', p):
                for d, e in self.switch_for(ref, path_try):
                    cands.append((d, e, path_try))
            if cands:
                for d, e, child in cands:
                    self.walk_object(resource, d, child, e, child, depth + 1, frozenset(), frozenset(self.entity_roots.get(e, {d})))
                return
            self.walk_object(resource, ref, p + '.entry[].value', entity, prefix, depth + 1, ancestors, ent_roots)
            return
        if ref in self.objects:
            cands = self.switch_for(ref, p)
            if cands:
                for d, e in cands:
                    self.walk_object(resource, d, p, e, p, depth + 1, frozenset(), frozenset(self.entity_roots.get(e, {d})))
                return
            self.walk_object(resource, ref, p, entity, prefix, depth + 1, ancestors, ent_roots)
        else:
            self.leaf(resource, f, p, entity, prefix)

    def leaf(self, resource, f, p, entity, prefix):
        hit = self.entity_at(f.get('ref') or '', p) if f.get('ref') else None
        if hit:
            entity, prefix = hit, p
        if entity is None:
            self.unmapped.append((resource['id'], p, 'no entity root covers this path'))
            return
        self.add(entity, self.rel_of(p, prefix, f['name']), p, f, resource['id'])

    def walk_resource(self, r):
        resp = r.get('response') or {}
        obj = resp.get('object')
        if not obj or obj not in self.objects:
            return
        start = resp.get('jsonRoot') or ''
        entity = self.entity_at(obj, start)
        prefix = norm(start) if entity else ''
        if entity is None:
            entity = self.entity_at(obj, '')
            prefix = ''
        self.walk_object(r, obj, start, entity, prefix, 0, frozenset(), frozenset({obj}) if entity else frozenset())

    def run(self):
        for r in self.resources.values():
            if r.get('readOnly') is False:
                continue
            self.walk_resource(r)
        return self.rows, self.unmapped


def container_ids(reg):
    return {'%s.%s' % (eid, rel): (eid, rel) for (eid, rel) in reg.containers}


def build_registry(rest, legacy, ui2_files):
    reg = Registry(rest)
    rows, unmapped = reg.run()

    def page_items(files):
        for pf in files:
            d = load(pf)
            for p in d.get('pages', []) or []:
                for s in p.get('sections', []) or []:
                    for it in s.get('items', []) or []:
                        yield pf, p, s, it

    # declared derived ids (any file may declare them; duplicates are a builder error)
    for pf in [os.path.join(INV, 'legacy-pages.yaml'), os.path.join(INV, 'ui2.yaml'),
               os.path.join(INV, 'ui2-extra.yaml')] + sorted(glob.glob(os.path.join(SRC, 'legacy-*.yaml'))):
        if not os.path.exists(pf):
            continue
        d = load(pf)
        for dv in d.get('derived', []) or []:
            ent = dv.get('entity') or dv['id'].split('.derived.')[0]
            row = rows.get(dv['id'])
            if row is None:
                rows[dv['id']] = row = {
                    'id': dv['id'], 'entity': ent, 'path': 'derived.' + dv['id'].split('.derived.')[1],
                    'origin': 'derived', 'rest': [], 'type': dv.get('type', 'string'),
                    'unit': dv.get('unit', ''), 'nullable': bool(dv.get('nullable', False)),
                    'when': dv.get('when', []), 'shownBy': [], 'legacyItems': [], 'ui2Items': [],
                    'format': dv.get('format', 'none'), 'normaliser': dv.get('normaliser', 'none'),
                    'status': 'required', 'derivation': dv.get('derivation', ''), 'note': dv.get('note', ''),
                }
            else:
                row['derivation'] = dv.get('derivation', '')
            if dv.get('restGap'):
                row['restGap'] = True
            if dv.get('altSource'):
                row['altSource'] = dv['altSource']

    all_pages = [os.path.join(INV, 'legacy-pages.yaml')] + [f for f in ui2_files if os.path.exists(f)]
    for pf, page, sec, it in page_items(all_pages):
        is_legacy = page['id'].startswith('legacy.')
        for fid in [it.get('field')] + list(it.get('fields') or []):
            if not fid:
                continue
            row = rows.get(fid)
            if row is None and fid in container_ids(reg):
                eid, rel = container_ids(reg)[fid]
                rows[fid] = row = {
                    'id': fid, 'entity': eid, 'path': rel, 'origin': 'rest', 'rest': reg.containers[(eid, rel)],
                    'type': 'object', 'unit': '', 'nullable': False, 'when': [], 'shownBy': [],
                    'legacyItems': [], 'ui2Items': [], 'format': 'none', 'normaliser': 'none',
                    'status': 'required', 'composite': True,
                    'note': 'COMPOSITE id: YARN renders this whole Resource/object as one formatted string '
                            '(format resource-string / mb). The primitive ids underneath remain the canonical leaf ids '
                            'and must also be stamped; this id exists so the composite cell itself is comparable.',
                }
            if row is None:
                if fid.startswith('static.'):
                    rows[fid] = row = {
                        'id': fid, 'entity': 'static', 'path': fid[len('static.'):], 'origin': 'static',
                        'rest': [], 'type': 'string', 'unit': '', 'nullable': False, 'when': [],
                        'shownBy': [], 'legacyItems': [], 'ui2Items': [], 'format': it.get('format', 'none'),
                        'normaliser': it.get('normaliser', 'none'), 'status': 'required', 'note': '',
                    }
                else:
                    continue    # validate.py reports unresolved ids
            tag = 'legacy' if is_legacy else 'ui2'
            if tag not in row['shownBy']:
                row['shownBy'].append(tag)
            key = 'legacyItems' if is_legacy else 'ui2Items'
            if it['id'] not in row[key]:
                row[key].append(it['id'])
            if row['format'] in ('none', '') and it.get('format') and it['format'] != 'none':
                row['format'] = it['format']
            if row['normaliser'] in ('none', '') and it.get('normaliser') and it['normaliser'] != 'none':
                row['normaliser'] = it['normaliser']

    # overrides
    ov_path = os.path.join(SRC, 'field-overrides.yaml')
    overrides = load(ov_path) if os.path.exists(ov_path) else {'version': 1}
    for fid, ov in (overrides.get('fields') or {}).items():
        row = rows.setdefault(fid, {
            'id': fid, 'entity': fid.split('.')[0], 'path': '.'.join(fid.split('.')[1:]), 'origin': 'rest',
            'rest': [], 'type': 'any', 'unit': '', 'nullable': False, 'when': [], 'shownBy': [],
            'legacyItems': [], 'ui2Items': [], 'format': 'none', 'normaliser': 'none', 'status': 'waivable',
        })
        for k in ('format', 'normaliser', 'unit', 'note'):
            if ov.get(k):
                row[k] = ov[k]
        if ov.get('status'):
            row['status'] = ov['status']
        if ov.get('waiver'):
            row['waiver'] = ov['waiver']
    # ids that no JSON walk can discover (XML-shaped daemon responses, scraped HTML listings, dynamic JMX
    # attributes, client-side model fields): declared explicitly in src/field-overrides.yaml -> `extraFields`.
    for fid, spec in (overrides.get('extraFields') or {}).items():
        row = rows.setdefault(fid, {
            'id': fid, 'entity': spec.get('entity', fid.split('.')[0]),
            'path': spec.get('path', '.'.join(fid.split('.')[1:])), 'origin': spec.get('origin', 'rest'),
            'rest': spec.get('rest', []), 'type': spec.get('type', 'string'), 'unit': spec.get('unit', ''),
            'nullable': bool(spec.get('nullable', False)), 'when': spec.get('when', []), 'shownBy': [],
            'legacyItems': [], 'ui2Items': [], 'format': spec.get('format', 'none'),
            'normaliser': spec.get('normaliser', 'none'), 'status': spec.get('status', 'required'),
        })
        if spec.get('note'):
            row['note'] = spec['note']
        if spec.get('derivation'):
            row['derivation'] = spec['derivation']
        if spec.get('altSource'):
            row['altSource'] = spec['altSource']
        if spec.get('waiver'):
            row['waiver'] = spec['waiver']
        if spec.get('composite'):
            row['composite'] = True
    waived_paths = {e['path']: e for e in (overrides.get('unmappedPaths') or [])}
    for g in overrides.get('groups') or []:
        for row in rows.values():
            if row['status'] != 'waivable':
                continue
            if any(row['id'].startswith(pfx) for pfx in g.get('prefixes') or []):
                row['waiver'] = {'category': g['category'], 'reason': g['reason']}

    # ids consumed as inputs of a declared derived value are "rendered-elsewhere", not unused
    consumed_by = {}
    for pf in [os.path.join(INV, 'legacy-pages.yaml')] + [f for f in ui2_files if os.path.exists(f)]:
        d = load(pf)
        for dv in d.get('derived', []) or []:
            for src in dv.get('from') or []:
                consumed_by.setdefault(src, []).append(dv['id'])

    for row in rows.values():
        if row['shownBy']:
            row['status'] = 'required'
            row.pop('waiver', None)
            continue
        row['status'] = 'waivable'
        if row.get('waiver'):
            continue
        res_ids = {e['resource'] for e in row['rest']}
        if row['id'] in consumed_by:
            row['waiver'] = {'category': 'rendered-elsewhere',
                             'reason': 'consumed as an input of derived value(s) %s' % ', '.join(consumed_by[row['id']])}
            continue
        # a leaf inside a container that is itself rendered as one formatted string (composite id)
        parts = row['id'].split('.')
        for i in range(len(parts) - 1, 0, -1):
            cand = '.'.join(parts[:i])
            c = rows.get(cand)
            if c is not None and c.get('composite') and c['status'] == 'required':
                row['waiver'] = {'category': 'rendered-elsewhere',
                                 'reason': 'included in the formatted text of composite cell %s (%s); the SPA also '
                                           'stamps the primitive datum, but the legacy text is the composite string'
                                           % (cand, ', '.join(c.get('shownBy') or ['rest-only']))}
                break
        if row.get('waiver'):
            continue
        if 'resourceInformations' in row['id']:
            row['waiver'] = {'category': 'rendered-elsewhere',
                             'reason': 'raw per-resource-type list (ResourceInformationsInfo); no YARN page shows it '
                                       'item by item - the formatted Resource string (memory/vCores + custom '
                                       'resources) is what the UI renders.'}
            continue
        if row['entity'] in ('static',):
            row['waiver'] = {'category': 'other', 'reason': 'declared but not referenced by any inventoried item'}
            continue
        if row.get('synthetic'):
            row['waiver'] = {'category': 'internal',
                             'reason': 'JAXB polymorphism discriminator injected by the JSON provider from @XmlType; '
                                       'consumed structurally (to pick the right entity shape), never rendered as data'}
            continue
        if res_ids and all((reg.resources.get(x, {}) or {}).get('readOnly') is False for x in res_ids):
            row['waiver'] = {'category': 'write-only',
                             'reason': 'only exposed by write endpoints (%s); the product is read-only' % ', '.join(sorted(res_ids))}
        elif row['origin'] == 'rest':
            row['waiver'] = {'category': 'unused-by-any-ui',
                             'reason': 'not rendered by any inventoried legacy/UI2 item; PLAN §8 P1 will fail the build if the '
                                       'harness ever observes it unrendered, so review before shipping'}
        else:
            row['waiver'] = {'category': 'other', 'reason': 'declared but not referenced by any inventoried item'}

    ordered = sorted(rows.values(), key=lambda r: r['id'])
    known_paths = {}
    for row in ordered:
        for e in row['rest']:
            known_paths.setdefault(norm(e['jsonPath']), row['id'])
    path_waivers, leftover, seen = [], [], set()
    for rid, p, why in unmapped:
        if (rid, p) in seen:
            continue
        seen.add((rid, p))
        ov = waived_paths.get(p)
        if ov:
            path_waivers.append({'resource': rid, 'path': p,
                                 'waiver': {'category': ov.get('category', 'other'), 'reason': ov['reason']}})
            continue
        np = norm(p)
        hid = known_paths.get(np)
        if not hid:
            for k, v in known_paths.items():
                if k.endswith('.' + np) or np.endswith('.' + k):
                    hid = v
                    break
        if hid:
            path_waivers.append({'resource': rid, 'path': p,
                                 'waiver': {'category': 'rendered-elsewhere',
                                            'reason': 'the same JSON key is registered as %s through another '
                                                      'resource/root of the same entity' % hid}})
            continue
        leftover.append((rid, p, why))
    out = {'version': 1, 'generated': GENERATED, 'fields': ordered,
           'unmappedPaths': sorted(path_waivers, key=lambda e: (e['resource'], e['path']))}
    return out, leftover, waived_paths, reg


def main():
    rest = merge_rest()
    dump_yaml(os.path.join(INV, 'rest-schema.yaml'), rest, GENERATED)
    legacy = merge_legacy()
    dump_yaml(os.path.join(INV, 'legacy-pages.yaml'), legacy, GENERATED)
    registry, leftover, waived, reg = build_registry(
        rest, legacy, [os.path.join(INV, 'ui2.yaml'), os.path.join(INV, 'ui2-extra.yaml')])
    dump_yaml(os.path.join(INV, 'field-ids.yaml'), registry, GENERATED)

    rows = registry['fields']
    print('rest-schema.yaml: %d entities, %d objects, %d object fields, %d resources, %d derived'
          % (len(rest['entities']), len(rest['objects']),
             sum(len(o['fields']) for o in rest['objects'].values()), len(rest['resources']), len(rest['derived'])))
    print('legacy-pages.yaml: %d pages, %d sections, %d items'
          % (len(legacy['pages']), sum(len(p['sections']) for p in legacy['pages']),
             sum(len(s['items']) for p in legacy['pages'] for s in p['sections'])))
    print('field-ids.yaml: %d rows (rest %d, derived %d, static %d) | required %d, waivable %d'
          % (len(rows), sum(r['origin'] == 'rest' for r in rows), sum(r['origin'] == 'derived' for r in rows),
             sum(r['origin'] == 'static' for r in rows), sum(r['status'] == 'required' for r in rows),
             sum(r['status'] == 'waivable' for r in rows)))
    used = {o for o in reg.objects}
    reachable = set()
    for r in reg.resources.values():
        o = ((r.get('response') or {}).get('object'))
        if o:
            reachable.add(o)
    print('objects referenced by a GET resource response: %d/%d; unreachable=write-only/nested-only' % (len(reachable), len(used)))
    if leftover:
        print('REST paths with no field id yet (%d):' % len(leftover))
        for rid, p, why in leftover:
            print('   %-24s %-70s %s' % (rid, p, why))
    else:
        print('REST paths with no field id: 0 (all either registered or waived in src/field-overrides.yaml)')


if __name__ == '__main__':
    main()
